// What replaces the Chebyshev structure when the first Betti number is >= 2?
//
// For Betti number b, gauge fixing leaves b free permutations, so an r-lift is exactly an action
// of the free group F_b on [r].  Connected components of the lift = orbits of that action.  The
// exponential formula for species therefore still applies, with "connected" = "transitive":
//
//     sum_r N_r z^r/r! = exp( sum_l C_l z^l/l! ),
//     N_r = sum over ALL b-tuples of permutations of prod_{orbits} chi(cover over orbit) = (r!)^b * Phi_r,
//     C_l = sum over TRANSITIVE b-tuples on [l] of chi(connected cover).
//
// In coefficient form (split off the component containing the point 1):
//
//     N_r = sum_{l=1..r} binomial(r-1, l-1) * C_l * N_{r-l}.
//
// b = 1: the transitive Z-actions on [l] are the (l-1)! l-cycles, all giving the SAME cover G_l,
// so C_l = (l-1)! * chi(G_l) and the formula collapses to sum_l chi(G_l) z^l / l -- one graph per
// l, whose char poly is Chebyshev in l.  That is the entire reason the cycle case closes.
//
// b >= 2: C_l is a sum over many non-isomorphic connected l-covers.  This program verifies the
// recurrence above for b = 2 and 3, and counts the covers, to show precisely what is lost.

use std::collections::HashMap;

type Poly = Vec<i128>;

fn pnorm(mut p: Poly) -> Poly { while p.len() > 1 && *p.last().unwrap() == 0 { p.pop(); } p }
fn padd(a: &Poly, b: &Poly) -> Poly {
    let n = a.len().max(b.len());
    pnorm((0..n).map(|i| a.get(i).copied().unwrap_or(0) + b.get(i).copied().unwrap_or(0)).collect())
}
fn pscale(a: &Poly, k: i128) -> Poly { pnorm(a.iter().map(|c| c * k).collect()) }
fn pmul(a: &Poly, b: &Poly) -> Poly {
    let mut r = vec![0i128; a.len() + b.len() - 1];
    for (i, &x) in a.iter().enumerate() { if x != 0 {
        for (j, &y) in b.iter().enumerate() { r[i + j] += x * y; } } }
    pnorm(r)
}

fn charpoly(m: &Vec<Vec<i128>>) -> Poly {
    let n = m.len();
    let mut acc = vec![vec![0i128; n]; n];
    let mut coeffs = vec![0i128; n + 1];
    coeffs[n] = 1;
    let mut c = 1i128;
    for k in 1..=n {
        let mut t = vec![vec![0i128; n]; n];
        for i in 0..n { for l in 0..n { let v = m[i][l]; if v != 0 {
            for j in 0..n { t[i][j] += v * acc[l][j]; } } } }
        for i in 0..n { t[i][i] += c; }
        acc = t;
        let mut tr = 0i128;
        for i in 0..n { for l in 0..n { tr += m[i][l] * acc[l][i]; } }
        c = -tr / (k as i128);
        coeffs[n - k] = c;
    }
    pnorm(coeffs)
}

fn perms(r: usize) -> Vec<Vec<usize>> {
    let mut out = vec![];
    let mut cur: Vec<usize> = (0..r).collect();
    fn rec(k: usize, cur: &mut Vec<usize>, out: &mut Vec<Vec<usize>>) {
        if k == cur.len() { out.push(cur.clone()); return; }
        for i in k..cur.len() { cur.swap(k, i); rec(k + 1, cur, out); cur.swap(k, i); }
    }
    rec(0, &mut cur, &mut out); out
}

struct Graph { n: usize, edges: Vec<(usize, usize)>, free: Vec<usize> }

/// lift adjacency: free edge j carries perms[j], all other edges identity
fn lift_adj(g: &Graph, r: usize, ps: &[Vec<usize>], sel: &[usize]) -> Vec<Vec<i128>> {
    let n = g.n * r;
    let mut a = vec![vec![0i128; n]; n];
    for (ei, &(u, v)) in g.edges.iter().enumerate() {
        let p: &Vec<usize> = match g.free.iter().position(|&f| f == ei) {
            Some(k) => &ps[sel[k]],
            None => &ps[0], // identity is perms[0] = (0,1,2,...)
        };
        for i in 0..r { let (x, y) = (u * r + i, v * r + p[i]); a[x][y] += 1; a[y][x] += 1; }
    }
    a
}

/// is the group generated by the given permutations transitive on [r]?
fn transitive(ps: &[&Vec<usize>], r: usize) -> bool {
    let mut seen = vec![false; r];
    let mut stack = vec![0usize];
    seen[0] = true;
    let mut cnt = 1;
    while let Some(v) = stack.pop() {
        for p in ps {
            for &w in [p[v], (0..r).find(|&i| p[i] == v).unwrap()].iter() {
                if !seen[w] { seen[w] = true; cnt += 1; stack.push(w); }
            }
        }
    }
    cnt == r
}

fn binom(n: usize, k: usize) -> i128 {
    if k > n { return 0; }
    let mut r = 1i128;
    for i in 0..k { r = r * (n - i) as i128 / (i + 1) as i128; }
    r
}

/// N_r = sum over all b-tuples of char poly of the lift
fn n_of_r(g: &Graph, r: usize) -> Poly {
    let ps = perms(r);
    let b = g.free.len();
    let mut sel = vec![0usize; b];
    let mut total: Poly = vec![0];
    loop {
        total = padd(&total, &charpoly(&lift_adj(g, r, &ps, &sel)));
        let mut k = 0;
        loop {
            if k == b { return total; }
            sel[k] += 1;
            if sel[k] < ps.len() { break; }
            sel[k] = 0; k += 1;
        }
    }
}

/// C_l = sum over TRANSITIVE b-tuples of char poly of the (connected) cover; also count them
fn c_of_l(g: &Graph, l: usize) -> (Poly, usize, usize) {
    let ps = perms(l);
    let b = g.free.len();
    let mut sel = vec![0usize; b];
    let mut total: Poly = vec![0];
    let mut ntrans = 0usize;
    let mut distinct: HashMap<Poly, usize> = HashMap::new();
    loop {
        let chosen: Vec<&Vec<usize>> = (0..b).map(|k| &ps[sel[k]]).collect();
        if transitive(&chosen, l) {
            let cp = charpoly(&lift_adj(g, l, &ps, &sel));
            *distinct.entry(cp.clone()).or_insert(0) += 1;
            total = padd(&total, &cp);
            ntrans += 1;
        }
        let mut k = 0;
        loop {
            if k == b { return (total, ntrans, distinct.len()); }
            sel[k] += 1;
            if sel[k] < ps.len() { break; }
            sel[k] = 0; k += 1;
        }
    }
}

fn main() {
    let graphs: Vec<(&str, Graph)> = vec![
        // unicyclic control: b = 1
        ("tadpole T(3,1) [b=1]", Graph { n: 4, edges: vec![(0,1),(1,2),(2,0),(0,3)], free: vec![2] }),
        // theta graph: spanning tree (0,1),(0,2),(0,3); free = (2,1),(3,1)
        ("theta graph [b=2]",    Graph { n: 4, edges: vec![(0,1),(0,2),(2,1),(0,3),(3,1)], free: vec![2,4] }),
        // bowtie: two triangles sharing vertex 2; tree (0,1),(1,2),(2,3),(3,4); free = (2,0),(4,2)
        ("bowtie [b=2]",         Graph { n: 5, edges: vec![(0,1),(1,2),(2,0),(2,3),(3,4),(4,2)], free: vec![2,5] }),
        ("K_4 [b=3]",            Graph { n: 4, edges: vec![(0,1),(0,2),(0,3),(1,2),(1,3),(2,3)], free: vec![3,4,5] }),
    ];

    for (name, g) in graphs.iter() {
        let b = g.free.len();
        let rmax = if b == 1 { 5 } else if b == 2 { 4 } else { 3 };
        println!("=== {}  (first Betti number {}) ===", name, b);

        let mut nn: Vec<Poly> = vec![vec![1]]; // N_0 = 1 (empty lift)
        for r in 1..=rmax { nn.push(n_of_r(g, r)); }
        let mut cc: Vec<Poly> = vec![vec![0]];
        let mut stats = vec![];
        for l in 1..=rmax { let (c, nt, nd) = c_of_l(g, l); cc.push(c); stats.push((l, nt, nd)); }

        // check N_r = sum_l binom(r-1,l-1) C_l N_{r-l}
        let mut ok = true;
        for r in 1..=rmax {
            let mut acc: Poly = vec![0];
            for l in 1..=r {
                acc = padd(&acc, &pscale(&pmul(&cc[l], &nn[r - l]), binom(r - 1, l - 1)));
            }
            if acc != nn[r] { ok = false; }
        }
        println!("  exponential formula  N_r = sum_l C(r-1,l-1) C_l N_{{r-l}}  for r=1..{}: {}",
                 rmax, if ok { "HOLDS" } else { "FAILS" });

        for (l, nt, nd) in stats {
            println!("     l={}: {:>6} transitive tuples, {:>4} distinct char polys among the connected l-covers", l, nt, nd);
        }
        println!();
    }

    println!("Reading: the exponential formula survives for every Betti number. What dies at b >= 2");
    println!("is the atom: for b = 1 every connected l-cover is THE cyclic cover G_l (one char poly");
    println!("per l, Chebyshev in l), whereas for b >= 2 the number of distinct connected l-covers");
    println!("grows, so C_l is an unstructured sum and no closed form follows.");
}
